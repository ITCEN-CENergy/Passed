-- 원본 명세에서 user_evidences가 참조하지만 누락된 사용자 특성 테이블.
CREATE TABLE user_features (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 bigint NOT NULL,
    feature_type            varchar(30) NOT NULL,
    feature_name            varchar(100) NOT NULL,
    feature_value           text,
    extraction_confidence   numeric(4,3),
    is_verified             boolean NOT NULL DEFAULT false,
    verified_at             timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_user_features_key
        UNIQUE (user_id, feature_type, feature_name),
    CONSTRAINT fk_user_features_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT chk_user_features_type
        CHECK (feature_type IN (
            'STRENGTH', 'WORK_STYLE', 'VALUE', 'INTEREST', 'TRAIT'
        )),
    CONSTRAINT chk_user_features_confidence
        CHECK (extraction_confidence IS NULL OR extraction_confidence BETWEEN 0 AND 1),
    CONSTRAINT chk_user_features_verification
        CHECK (
            (is_verified AND verified_at IS NOT NULL)
            OR (NOT is_verified AND verified_at IS NULL)
        )
);

CREATE INDEX ix_user_features_user ON user_features (user_id);

CREATE TABLE user_skills (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             bigint NOT NULL,
    skill_id            bigint NOT NULL,
    skill_level         smallint NOT NULL DEFAULT 1,
    importance_level    smallint NOT NULL DEFAULT 2,
    mapping_similarity  numeric(4,3),
    is_verified         boolean NOT NULL DEFAULT false,
    verified_at         timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_user_skills_skill UNIQUE (user_id, skill_id),
    CONSTRAINT fk_user_skills_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_skills_skill
        FOREIGN KEY (skill_id) REFERENCES skills(id) ON DELETE RESTRICT,
    CONSTRAINT chk_user_skills_level CHECK (skill_level BETWEEN 1 AND 3),
    CONSTRAINT chk_user_skills_importance CHECK (importance_level BETWEEN 1 AND 3),
    CONSTRAINT chk_user_skills_similarity
        CHECK (mapping_similarity IS NULL OR mapping_similarity BETWEEN 0 AND 1),
    CONSTRAINT chk_user_skills_verification
        CHECK (
            (is_verified AND verified_at IS NOT NULL)
            OR (NOT is_verified AND verified_at IS NULL)
        )
);

CREATE INDEX ix_user_skills_user ON user_skills (user_id);
CREATE INDEX ix_user_skills_skill ON user_skills (skill_id);
CREATE INDEX ix_user_skills_importance ON user_skills (importance_level);
CREATE INDEX ix_user_skills_verified ON user_skills (is_verified);

CREATE TABLE user_evidences (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_skill_id           bigint,
    user_feature_id         bigint,
    source_type             varchar(30) NOT NULL,
    source_id               bigint NOT NULL,
    evidence_text           text NOT NULL,
    evidence_summary        text,
    extraction_confidence   numeric(4,3),
    is_primary              boolean NOT NULL DEFAULT false,
    is_important_source     boolean NOT NULL DEFAULT false,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fk_user_evidences_skill
        FOREIGN KEY (user_skill_id) REFERENCES user_skills(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_evidences_feature
        FOREIGN KEY (user_feature_id) REFERENCES user_features(id) ON DELETE CASCADE,
    CONSTRAINT chk_user_evidences_owner_xor
        CHECK ((user_skill_id IS NOT NULL) <> (user_feature_id IS NOT NULL)),
    CONSTRAINT chk_user_evidences_source_type
        CHECK (source_type IN (
            'EDUCATION', 'EXPERIENCE', 'ACTIVITY', 'TRAINING',
            'CERTIFICATION', 'AWARD', 'OVERSEAS_EXPERIENCE',
            'LANGUAGE', 'COVER_LETTER'
        )),
    CONSTRAINT chk_user_evidences_confidence
        CHECK (extraction_confidence IS NULL OR extraction_confidence BETWEEN 0 AND 1)
);

CREATE INDEX ix_user_evidences_skill ON user_evidences (user_skill_id);
CREATE INDEX ix_user_evidences_feature ON user_evidences (user_feature_id);
CREATE INDEX ix_user_evidences_source ON user_evidences (source_type, source_id);
CREATE INDEX ix_user_evidences_primary ON user_evidences (is_primary);
CREATE UNIQUE INDEX uq_user_evidences_skill_source
    ON user_evidences (user_skill_id, source_type, source_id)
    WHERE user_skill_id IS NOT NULL;
CREATE UNIQUE INDEX uq_user_evidences_feature_source
    ON user_evidences (user_feature_id, source_type, source_id)
    WHERE user_feature_id IS NOT NULL;

