CREATE TABLE users (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            varchar(100) NOT NULL,
    email           varchar(255) NOT NULL,
    password        varchar(255) NOT NULL,
    field           varchar(100),
    desired_jobs    jsonb,
    created_at      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_email_not_blank CHECK (btrim(email) <> ''),
    CONSTRAINT chk_users_desired_jobs_array
        CHECK (desired_jobs IS NULL OR jsonb_typeof(desired_jobs) = 'array')
);

COMMENT ON COLUMN users.password IS 'bcrypt, Argon2id 등 단방향 해시만 저장';
COMMENT ON COLUMN users.desired_jobs IS '희망 직무 키워드 JSON 배열';

CREATE TABLE cover_letter_questions (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_type   varchar(30) NOT NULL,
    question_text   varchar(500) NOT NULL,
    guide_text      text,
    match_weight    numeric(3,2),
    display_order   integer,
    is_active       boolean NOT NULL DEFAULT true,

    CONSTRAINT uq_cover_letter_questions_type UNIQUE (question_type),
    CONSTRAINT chk_cover_letter_questions_type
        CHECK (question_type IN ('MOTIVATION', 'PERSONALITY', 'EXPERIENCE')),
    CONSTRAINT chk_cover_letter_questions_weight
        CHECK (match_weight IS NULL OR match_weight BETWEEN 0 AND 1),
    CONSTRAINT chk_cover_letter_questions_order
        CHECK (display_order IS NULL OR display_order >= 0)
);

CREATE TABLE cover_letters (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_cover_letters_user UNIQUE (user_id),
    CONSTRAINT fk_cover_letters_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE cover_letter_items (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cover_letter_id   bigint NOT NULL,
    question_id       bigint NOT NULL,
    answer            text,
    relevance_score   numeric(4,3),
    embedding         vector(1536),
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_cover_letter_items_question
        UNIQUE (cover_letter_id, question_id),
    CONSTRAINT fk_cover_letter_items_cover_letter
        FOREIGN KEY (cover_letter_id) REFERENCES cover_letters(id) ON DELETE CASCADE,
    CONSTRAINT fk_cover_letter_items_question
        FOREIGN KEY (question_id) REFERENCES cover_letter_questions(id) ON DELETE RESTRICT,
    CONSTRAINT chk_cover_letter_items_relevance
        CHECK (relevance_score IS NULL OR relevance_score BETWEEN 0 AND 1)
);

CREATE INDEX ix_cover_letter_items_cover_letter
    ON cover_letter_items (cover_letter_id);

