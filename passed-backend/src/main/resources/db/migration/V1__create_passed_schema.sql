-- Passed PostgreSQL initial schema
-- PostgreSQL 15+ / pgvector
--
-- 설계 원칙:
-- 1. 애플리케이션 상태값은 PostgreSQL ENUM 대신 CHECK 제약으로 관리하여 변경을 쉽게 한다.
-- 2. 사용자 입력 데이터 삭제 시 하위 데이터는 CASCADE, 마스터 데이터 삭제는 RESTRICT한다.
-- 3. source_type + source_id 형태의 다형 참조는 DB 외래키로 표현할 수 없으므로
--    source_type 값만 CHECK하고 source_id 실재 여부는 서비스 계층에서 검증한다.

CREATE EXTENSION IF NOT EXISTS vector;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

