CREATE TABLE job_postings (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               varchar(255) NOT NULL,
    company_id          bigint NOT NULL,
    job_role_id         bigint NOT NULL,
    start_ymd           varchar(8),
    end_ymd             varchar(8),
    headcount           integer,
    career_type         varchar(50),
    hire_type           varchar(255),
    region              varchar(255),
    edu_level           varchar(255),
    position_detail     text,
    main_duty           text,
    qualification       text,
    preference          text,
    disqualify_reason   text,
    process             text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fk_job_postings_company
        FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE RESTRICT,
    CONSTRAINT fk_job_postings_role
        FOREIGN KEY (job_role_id) REFERENCES job_roles(id) ON DELETE RESTRICT,
    CONSTRAINT chk_job_postings_start_ymd
        CHECK (
            start_ymd IS NULL
            OR (
                start_ymd ~ '^[0-9]{8}$'
                AND to_char(to_date(start_ymd, 'YYYYMMDD'), 'YYYYMMDD') = start_ymd
            )
        ),
    CONSTRAINT chk_job_postings_end_ymd
        CHECK (
            end_ymd IS NULL
            OR (
                end_ymd ~ '^[0-9]{8}$'
                AND to_char(to_date(end_ymd, 'YYYYMMDD'), 'YYYYMMDD') = end_ymd
            )
        ),
    CONSTRAINT chk_job_postings_headcount
        CHECK (headcount IS NULL OR headcount >= 0)
);

CREATE INDEX ix_job_postings_company ON job_postings (company_id);
CREATE INDEX ix_job_postings_role ON job_postings (job_role_id);
CREATE INDEX ix_job_postings_end_ymd ON job_postings (end_ymd);
CREATE INDEX ix_job_postings_career_type ON job_postings (career_type);

CREATE TABLE job_posting_chunks (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_posting_id      bigint NOT NULL,
    source_type         varchar(50) NOT NULL,
    chunk_index         integer NOT NULL DEFAULT 0,
    chunk_content       text NOT NULL,
    use_for_matching    boolean NOT NULL DEFAULT true,
    embedding           vector(1536),
    content_hash        varchar(64) NOT NULL,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_job_posting_chunks_key
        UNIQUE (job_posting_id, source_type, chunk_index),
    CONSTRAINT fk_job_posting_chunks_posting
        FOREIGN KEY (job_posting_id) REFERENCES job_postings(id) ON DELETE CASCADE,
    CONSTRAINT chk_job_posting_chunks_source_type
        CHECK (source_type IN (
            'POSITION_DETAIL', 'MAIN_TASK', 'REQUIREMENT', 'PREFERENCE',
            'TECH_STACK', 'BENEFIT', 'PROCESS', 'DISQUALIFICATION', 'ETC'
        )),
    CONSTRAINT chk_job_posting_chunks_index CHECK (chunk_index >= 0),
    CONSTRAINT chk_job_posting_chunks_hash
        CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_job_posting_chunks_matching_rule
        CHECK (
            (
                source_type IN ('PROCESS', 'DISQUALIFICATION', 'BENEFIT')
                AND use_for_matching = false
            )
            OR
            (
                source_type NOT IN ('PROCESS', 'DISQUALIFICATION', 'BENEFIT')
                AND use_for_matching = true
            )
        )
);

CREATE INDEX ix_job_posting_chunks_posting
    ON job_posting_chunks (job_posting_id);
CREATE INDEX ix_job_posting_chunks_source
    ON job_posting_chunks (source_type);
CREATE INDEX ix_job_posting_chunks_hash
    ON job_posting_chunks (content_hash);
CREATE INDEX ix_job_posting_chunks_embedding_pending
    ON job_posting_chunks (job_posting_id)
    WHERE embedding IS NULL AND chunk_content <> '' AND use_for_matching = true;

CREATE TABLE job_posting_extraction_meta (
    job_posting_id     bigint PRIMARY KEY,
    input_hash         varchar(64) NOT NULL,
    prompt_version     varchar(32) NOT NULL,
    extraction_model   varchar(64) NOT NULL,
    tech_stacks_json   jsonb NOT NULL DEFAULT '[]'::jsonb,
    benefits_json      jsonb NOT NULL DEFAULT '[]'::jsonb,
    created_at         timestamptz NOT NULL DEFAULT now(),
